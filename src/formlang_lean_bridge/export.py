from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Sequence
import json
import re


@dataclass(frozen=True)
class LeanArtifact:
    """Lean source plus a manifest mapping integer IDs to Python values."""

    source: str
    manifest: dict[str, Any]

    def write(self, path: str | Path) -> Path:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(self.source, encoding="utf-8")
        target.with_suffix(target.suffix + ".json").write_text(
            json.dumps(self.manifest, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        return target


def _unwrap(value: Any) -> Any:
    return getattr(value, "value", value)


def _sort_key(value: Any) -> tuple[str, str]:
    value = _unwrap(value)
    return type(value).__name__, repr(value)


def _lean_namespace(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_']", "_", name)
    if not name or not name[0].isalpha():
        name = "Exported_" + name
    return name


def _is_epsilon(symbol: Any) -> bool:
    value = _unwrap(symbol)
    return str(value).strip().lower() in {
        "epsilon", "eps", "ε", "ϵ", "ɛ", "λ", "lambda"
    }


def export_automaton(
    automaton: Any,
    name: str = "ExportedAutomaton",
    words: Iterable[Sequence[Any]] = (),
) -> LeanArtifact:
    """
    Export a Pyformlang DFA/NFA into executable Lean 4 definitions.

    This first version supports finite automata without epsilon transitions.
    It intentionally rejects epsilon edges rather than silently changing
    their meaning.
    """
    namespace = _lean_namespace(name)

    states = sorted(list(automaton.states), key=_sort_key)
    start_states = sorted(list(automaton.start_states), key=_sort_key)
    final_states = sorted(list(automaton.final_states), key=_sort_key)

    state_ids = {state: i for i, state in enumerate(states)}

    # Pyformlang finite automata are iterable over (source, symbol, target).
    edges = list(automaton)
    alphabet_set = set()
    for source, symbol, target in edges:
        if _is_epsilon(symbol):
            raise NotImplementedError(
                "Epsilon transitions are not supported by bridge 0.1.0. "
                "Convert the EpsilonNFA to an NFA first."
            )
        alphabet_set.add(symbol)

    alphabet = sorted(alphabet_set, key=_sort_key)
    symbol_ids = {symbol: i for i, symbol in enumerate(alphabet)}

    words = [list(word) for word in words]
    for word in words:
        for symbol in word:
            if symbol not in symbol_ids:
                raise ValueError(
                    f"Test word symbol {symbol!r} is not in the automaton alphabet"
                )

    transition_set = {
        (state_ids[source], symbol_ids[symbol], state_ids[target])
        for source, symbol, target in edges
    }
    transitions = sorted(transition_set)
    starts = sorted(state_ids[state] for state in start_states)
    finals = sorted(state_ids[state] for state in final_states)

    def nat_list(values: Sequence[int]) -> str:
        return "[" + ", ".join(str(v) for v in values) + "]"

    transition_literal = "[" + ", ".join(
        f"({source}, {symbol}, {target})"
        for source, symbol, target in transitions
    ) + "]"

    lines = [
        "/- Generated by formlang-lean-bridge. -/",
        "import Std",
        "",
        f"namespace {namespace}",
        "",
        f"def stateCount : Nat := {len(states)}",
        f"def symbolCount : Nat := {len(alphabet)}",
        f"def transitions : List (Nat × Nat × Nat) := {transition_literal}",
        f"def startStates : List Nat := {nat_list(starts)}",
        f"def finalStates : List Nat := {nat_list(finals)}",
        "",
        "def step (current : List Nat) (symbol : Nat) : List Nat :=",
        "  ((transitions.filter (fun edge =>",
        "      current.contains edge.1 && edge.2.1 == symbol)).map",
        "      (fun edge => edge.2.2)).eraseDups",
        "",
        "def run (current : List Nat) : List Nat → List Nat",
        "  | [] => current",
        "  | symbol :: rest => run (step current symbol) rest",
        "",
        "def accepts (word : List Nat) : Bool :=",
        "  (run startStates word).any (fun state => finalStates.contains state)",
        "",
    ]

    for word in words:
        ids = [symbol_ids[symbol] for symbol in word]
        expected = bool(automaton.accepts(word))
        lines.append(
            f"example : {namespace}.accepts {nat_list(ids)} = "
            f"{str(expected).lower()} := by decide"
        )

    lines.extend(["", f"end {namespace}", ""])

    manifest = {
        "format": "formlang-lean-bridge/0.1.0",
        "namespace": namespace,
        "states": [
            {"id": state_ids[state], "python_repr": repr(_unwrap(state))}
            for state in states
        ],
        "alphabet": [
            {"id": symbol_ids[symbol], "python_repr": repr(_unwrap(symbol))}
            for symbol in alphabet
        ],
        "start_state_ids": starts,
        "final_state_ids": finals,
        "transitions": [
            {"source": source, "symbol": symbol, "target": target}
            for source, symbol, target in transitions
        ],
    }
    return LeanArtifact(source="\n".join(lines), manifest=manifest)
